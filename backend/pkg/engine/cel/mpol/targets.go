type mutationTarget struct {
	object      unstructured.Unstructured
	resource    schema.GroupVersionResource
	subresource string
}

func (t mutationTarget) key() string {
	return strings.Join([]string{t.resource.Group, t.resource.Version, t.resource.Resource, t.object.GetNamespace(), t.object.GetName(), t.subresource}, "/")
}

// A target result must evaluate one compiled policy, including when the engine
// provider contains autogenerated variants with the same policy key.
type targetProvider struct {
	engine.Provider
	policy engine.Policy
}

func (p targetProvider) Fetch(context.Context, bool) []engine.Policy {
	return []engine.Policy{p.policy}
}

// Evaluate in Kyverno v1.19 supplies no namespace to its matcher and falls back
// to trigger rules for expression-only targets. Supply the target constraints
// and namespace here, while delegating all matching to Kyverno.
type targetMatcher struct {
	client      dclient.Interface
	constraints admissionregistrationv1.MatchResources
	ctx         context.Context
}

func (m targetMatcher) Match(_ policymatching.MatchCriteria, attr admission.Attributes, _ runtime.Object) (bool, error) {
	var namespace runtime.Object
	selector := m.constraints.NamespaceSelector
	if attr.GetNamespace() != "" && selector != nil && (len(selector.MatchLabels) != 0 || len(selector.MatchExpressions) != 0) {
		ns, err := m.client.GetResource(m.ctx, "v1", "Namespace", "", attr.GetNamespace())
		if err != nil {
			return false, err
		}
		namespace = ns
	}
	return matching.NewMatcher().Match(&matching.MatchCriteria{Constraints: &m.constraints}, attr, namespace)
}

func resolveTargets(ctx context.Context, client dclient.Interface, mapper meta.RESTMapper, policy engine.Policy, trigger admission.Attributes, request *admissionv1.AdmissionRequest) ([]mutationTarget, error) {
	constraints := policy.Policy.GetTargetMatchConstraints()
	var targets []mutationTarget
	if constraints.Expression != "" {
		objects, err := policy.CompiledPolicy.EvaluateTargetExpression(ctx, trigger, request, nil)
		if err != nil {
			return nil, err
		}
		if objects == nil {
			return nil, nil
		}
		list := unstructured.Unstructured{Object: objects}
		var items []unstructured.Unstructured
		if list.IsList() {
			decoded, err := list.ToList()
			if err != nil {
				return nil, err
			}
			items = decoded.Items
		} else {
			items = []unstructured.Unstructured{list}
		}
		for _, object := range items {
			mapping, err := mapper.RESTMapping(object.GroupVersionKind().GroupKind(), object.GroupVersionKind().Version)
			if err != nil {
				return nil, err
			}
			if ns := policy.Policy.GetNamespace(); ns != "" && object.GetNamespace() != ns {
				continue
			}
			subresource := targetSubresource(mapping.Resource, constraints.MatchResources)
			targets = append(targets, mutationTarget{object: object, resource: mapping.Resource, subresource: subresource})
		}
	} else {
		for _, rule := range constraints.ResourceRules {
			for _, group := range rule.APIGroups {
				for _, version := range rule.APIVersions {
					for _, resource := range rule.Resources {
						base, subresource, _ := strings.Cut(resource, "/")
						gvr := schema.GroupVersionResource{Group: group, Version: version, Resource: base}
						kind, err := mapper.KindFor(gvr)
						if err != nil {
							return nil, err
						}
						mapping, err := mapper.RESTMapping(kind.GroupKind(), kind.Version)
						if err != nil {
							return nil, err
						}
						namespace := policy.Policy.GetNamespace()
						if namespace != "" && mapping.Scope.Name() != meta.RESTScopeNameNamespace {
							continue
						}
						objects, err := client.ListResource(ctx, kind.GroupVersion().String(), kind.Kind, namespace, constraints.ObjectSelector)
						if err != nil {
							return nil, err
						}
						for _, object := range objects.Items {
							if len(rule.ResourceNames) != 0 && !slices.Contains(rule.ResourceNames, object.GetName()) {
								continue
							}
							targets = append(targets, mutationTarget{object: object, resource: mapping.Resource, subresource: subresource})
						}
					}
				}
			}
		}
	}
	for _, target := range targets {
		if target.object.GetName() == "" || target.object.GetKind() == "" {
			return nil, fmt.Errorf("target must be a Kubernetes object with kind and metadata.name")
		}
	}
	slices.SortFunc(targets, func(a, b mutationTarget) int { return strings.Compare(a.key(), b.key()) })
	return slices.CompactFunc(targets, func(a, b mutationTarget) bool { return a.key() == b.key() }), nil
}

func targetSubresource(resource schema.GroupVersionResource, constraints admissionregistrationv1.MatchResources) string {
	for _, rule := range constraints.ResourceRules {
		if !slices.ContainsFunc(rule.APIGroups, func(group string) bool { return wildcard.Match(group, resource.Group) }) ||
			!slices.ContainsFunc(rule.APIVersions, func(version string) bool { return wildcard.Match(version, resource.Version) }) {
			continue
		}
		for _, name := range rule.Resources {
			base, subresource, _ := strings.Cut(name, "/")
			if wildcard.Match(base, resource.Resource) {
				return subresource
			}
		}
	}
	return ""
}
